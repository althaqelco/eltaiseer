export function hubLede(o: { n: number; lastVerified: string | null; reviewed: string | undefined }): string {
  const head =
    "نعم، تُباع أرض بيت الوطن المخصصة بالتنازل الرسمي بموافقة كتابية مسبقة من جهاز المدينة (كراسة الشروط ص1، وص7 البند 3)، ولا يُباع كود الحجز نفسه (ص3). لا ننشر إعلانًا قبل خطاب التخصيص.";
  if (o.n > 0 && o.lastVerified) {
    return `${head} هنا ${verifiedAds(o.n)} حتى ${cairoDate(o.lastVerified)}، ومع كل إعلان التكلفة الفعلية للمتر مقارنة بسعر الهيئة. ${NO_FUNDS}`;
  }
  const rev = o.reviewed ? ` (آخر مراجعة ${cairoDate(o.reviewed)})` : "";
  return `${head} لا توجد إعلانات موثّقة منشورة الآن${rev}؛ سجّل طلب شراء ونبلغك أول ما تُوثَّق قطعة. ${NO_FUNDS}`;
}

