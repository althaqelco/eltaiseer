export const verifiedAds = (n: number) =>
  count(n, { one: "إعلان موثّق واحد", two: "إعلانان موثّقان", few: "إعلانات موثّقة", many: "إعلانًا موثّقًا" });

/** «490 دولارًا»، «500 دولار»، «3 دولارات» */
export function usd(n: number): string {
  const v = Math.round(n);
  const r = v % 100;
  if (v >= 100 && r <= 2) return `${fmtN(v)} دولار`;
  if (r >= 3 && r <= 10) return `${fmtN(v)} دولارات`;
  return `${fmtN(v)} دولارًا`;
}

